import { readFile, writeFile } from 'node:fs/promises';

const settings = JSON.parse(await readFile(new URL('../config/operations.config.json', import.meta.url), 'utf8'));
const rateLimits = JSON.parse(await readFile(new URL('../config/rate-limits.config.json', import.meta.url), 'utf8'));
for (const [key, value] of Object.entries(rateLimits)) {
  if (!('limit' in value)) continue;
  settings[key] = { value: value.limit, min: 1, max: 100000, group: 'rates' };
}
for (const [key, spec] of Object.entries(settings)) {
  if (!Number.isInteger(spec.value) || spec.value < spec.min || spec.value > spec.max) throw new Error(`Invalid operations policy: ${key}`);
}
const output = `// Generated by scripts/generate-operations.mjs.\nexport const OPERATION_POLICIES = ${JSON.stringify(settings, null, 2)} as const;\nexport type OperationPolicyKey = keyof typeof OPERATION_POLICIES;\nexport type OperationPolicies = Record<OperationPolicyKey, number>;\nexport const DEFAULT_OPERATION_POLICIES: OperationPolicies = Object.fromEntries(Object.entries(OPERATION_POLICIES).map(([key, spec]) => [key, spec.value])) as OperationPolicies;\n`;
for (const target of ['../src/generated/operations.ts', '../cloudflare/generated/operations.ts']) {
  await writeFile(new URL(target, import.meta.url), output);
}
