import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import less from "less";

// Compile the installed upstream Less sources; ship only the requested iOS
// theme and the components Novae uses. There is no hand-maintained CSS fork.
const components = [
  "card",
  "input",
  "toggle",
  "login-screen",
  "typography",
  "dialog",
  "actions",
  "sheet",
  "popup",
  "popover",
  "toast",
  "tooltip",
  "preloader",
  "progressbar",
  "fab",
  "messagebar",
  "radio",
  "smart-select",
  "photo-browser",
  "swiper",
  "accordion",
  "searchbar",
  "subnavbar",
  "skeleton",
];
const libraryRoot = path.dirname(
  fileURLToPath(import.meta.resolve("framework7/less")),
);
const core = [
  "app",
  "statusbar",
  "touch-highlight",
  "view",
  "link",
  "toolbar",
  "navbar",
  "page",
  "list",
  "badge",
  "button",
  "icon",
  "modal",
  "timeline",
  "block",
];
// Native modal views and Smart Select need the upstream view/page contracts.
const importPath = (relative) =>
  path.join(libraryRoot, relative).replaceAll("\\", "/");
const source = [
  `@import (reference) "${importPath("less/mixins.less")}";`,
  `@import (reference) "${importPath("less/vars.less")}";`,
  "@rtl: false;",
  ...[...core, ...components].flatMap((name) => {
    // Photo Browser uses slide/zoom/virtual, and our placeholders use blocks.
    // Select the installed upstream styles instead of shipping unused effects/fonts.
    if (name === "swiper") return [
      ...["swiper/css", "swiper/css/zoom", "swiper/css/virtual"].map((entry) =>
        `@import (inline) "${fileURLToPath(import.meta.resolve(entry)).replaceAll("\\", "/")}";`),
      `@import "${importPath("components/swiper/swiper-ios.less")}";`,
    ];
    if (name === "skeleton") {
      const skeletonRoot = path.dirname(fileURLToPath(import.meta.resolve("skeleton-elements/css")));
      return [
        ...["core", "block", "effect"].map((part) => `@import (inline) "${path.join(skeletonRoot, `skeleton-${part}.css`).replaceAll("\\", "/")}";`),
        `@import "${importPath("components/skeleton/skeleton-vars.less")}";`,
        `@import "${importPath("components/skeleton/skeleton-ios.less")}";`,
      ];
    }
    return [`@import "${importPath(`components/${name}/${name}.less`)}";`];
  }),
].join("\n");
const { css } = await less.render(source, {
  filename: fileURLToPath(import.meta.url),
  modifyVars: {
    includeIosTheme: true,
    includeMdTheme: false,
    includeDarkTheme: true,
    includeLightTheme: true,
  },
  math: "always",
});
const destination = path.resolve("src/generated/framework7-ios.css");
await mkdir(path.dirname(destination), { recursive: true });
const generated = `/* Generated by scripts/generate-framework7.mjs from Framework7's MIT-licensed sources. */\n${css}`;
const previous = await readFile(destination, "utf8").catch((error) => {
  if (error.code === "ENOENT") return null;
  throw error;
});
if (previous !== generated) await writeFile(destination, generated);
console.info("Generated Framework7 iOS stylesheet.");
